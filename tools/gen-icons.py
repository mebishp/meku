#!/usr/bin/env python3
"""Vendor the Iconoir glyphs Meku uses and generate `crates/meku/src/icons.rs`.

Usage: tools/gen-icons.py <path to unpacked iconoir npm package>
Iconoir (MIT, https://iconoir.com) is the icon set; add a (Variant, file) pair
below and re-run to extend it.
"""
import re, shutil, sys
from pathlib import Path

ICONS = [
    ("Note", "page"), ("NotePlus", "page-plus"), ("Notes", "notes"),
    ("Folder", "folder"), ("FolderPlus", "folder-plus"),
    ("Search", "search"), ("Plus", "plus"), ("Close", "xmark"), ("CloseCircle", "xmark-circle"),
    ("SidebarCollapse", "sidebar-collapse"), ("SidebarExpand", "sidebar-expand"),
    ("Source", "code-brackets"), ("Live", "edit-pencil"), ("Read", "book"), ("Eye", "eye"),
    ("Sun", "sun-light"), ("Moon", "half-moon"), ("Settings", "settings"), ("Palette", "palette"),
    ("ChevronRight", "nav-arrow-right"), ("ChevronDown", "nav-arrow-down"),
    ("ChevronLeft", "nav-arrow-left"), ("ChevronUp", "nav-arrow-up"),
    ("Copy", "copy"), ("Check", "check"), ("CheckCircle", "check-circle"),
    ("Outline", "list"), ("Pin", "pin"), ("Trash", "trash"), ("Maximize", "maximize"),
    ("ZoomIn", "zoom-in"), ("ZoomOut", "zoom-out"), ("Image", "media-image"), ("Link", "link"),
    ("More", "more-horiz"), ("Undo", "undo"), ("Redo", "redo"), ("Terminal", "terminal"),
    ("Back", "arrow-left"), ("Forward", "arrow-right"), ("Clock", "clock"),
    ("Bookmark", "bookmark"), ("Star", "star"), ("Info", "info-circle"),
    ("Warning", "warning-triangle"), ("Idea", "light-bulb"), ("Quote", "quote"),
    ("Table", "table-rows"), ("TaskList", "task-list"), ("Hash", "hashtag"),
    ("HelpCircle", "help-circle"), ("Bug", "bug"), ("Menu", "menu"), ("Refresh", "refresh"), ("Journal", "journal"),
    ("Minus", "minus"),
]

src = Path(sys.argv[1]) / "icons" / "regular"
root = Path(__file__).resolve().parent.parent / "crates" / "meku"
out_dir = root / "assets" / "icons" / "meku"
out_dir.mkdir(parents=True, exist_ok=True)
for old in out_dir.glob("*.svg"):
    old.unlink()
for _, name in ICONS:
    shutil.copy(src / f"{name}.svg", out_dir / f"{name}.svg")
shutil.copy(Path(sys.argv[1]) / "LICENSE", root / "assets" / "icons" / "LICENSE-iconoir")

variants = "\n".join(f"    {v}," for v, _ in ICONS)
paths = "\n".join(f'        Ico::{v} => "icons/meku/{n}.svg",' for v, n in ICONS)
loads = "\n".join(
    f'        "icons/meku/{n}.svg" => include_bytes!("../assets/icons/meku/{n}.svg"),' for _, n in ICONS
)
(root / "src" / "icons.rs").write_text(f'''//! Meku's icon set: Iconoir (MIT), vendored under `assets/icons/meku/`.
//! Generated by `tools/gen-icons.py` — edit the list there, not this file.

use std::borrow::Cow;

use anyhow::Result;
use gpui_kit::{{AssetSource, SharedString, Styled as _}};

/// The icon vocabulary; not every glyph is used everywhere yet.
#[allow(dead_code)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ico {{
{variants}
}}

impl Ico {{
    /// Asset path of the icon's SVG.
    pub fn path(self) -> &'static str {{
        match self {{
{paths}
        }}
    }}
}}

fn embedded(path: &str) -> Option<&'static [u8]> {{
    Some(match path {{
{loads}
        _ => return None,
    }})
}}

/// An icon of `size` in `color`.
pub fn icon(ico: Ico, size: gpui_kit::Pixels, color: gpui_kit::Hsla) -> gpui_kit::Svg {{
    gpui_kit::svg()
        .path(ico.path())
        .size(size)
        .flex_none()
        .text_color(color)
}}

/// Meku's icons first, then everything the kit ships (its own components
/// still draw their built-in icons).
pub struct MekuAssets;

impl AssetSource for MekuAssets {{
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {{
        match embedded(path) {{
            Some(bytes) => Ok(Some(Cow::Borrowed(bytes))),
            None => gpui_kit::assets::Assets.load(path),
        }}
    }}

    fn list(&self, path: &str) -> Result<Vec<SharedString>> {{
        gpui_kit::assets::Assets.list(path)
    }}
}}
''')
print("vendored", len(ICONS), "icons")
